import React, { useState } from 'react';
import { Download, FileText, ExternalLink, Upload, Search } from 'lucide-react';

export default function DocumentsView({ docs, onSelectDoc, onNavigateToAnalysis }) {
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedCategory, setSelectedCategory] = useState('ALL');
  const [downloadingId, setDownloadingId] = useState(null);

  // Helper to trigger realistic client-side downloadable file
  const handleDownload = (doc) => {
    setDownloadingId(doc.id);
    
    // Generate clean structured text representation of the document
    const content = `================================================================================
LEGALMIND / LUMIÈREAI — CLOUD DOCUMENT REPOSITORY (SUPABASE BACKED)
================================================================================
Document Title: ${doc.name}
Document Type : ${doc.type}
Metadata      : ${doc.meta}
Cloud Storage : Supabase Storage (hrfthahhweklgxkswfzb.supabase.co/storage/v1/s3)
Sync Status   : Synced & Indexed in ChromaDB
Statutory Code: Companies Act 2013 / Indian Contract Act 1872
================================================================================

CLAUSE BREAKDOWN & RISK HIGHLIGHTS:
${doc.risks.map((r, i) => `
[Clause ${i + 1}] ${r.title}
Severity : ${r.severity} RISK
Location : ${r.location}
Details  : ${r.desc}
--------------------------------------------------------------------------------`).join('\n')}

================================================================================
Generated by LumièreAI Automated Due Diligence Engine
Timestamp: ${new Date().toISOString()}
================================================================================`;

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${doc.name.replace(/[^a-zA-Z0-9_-]/g, '_')}_LumiereAI_Audited.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    setTimeout(() => {
      setDownloadingId(null);
    }, 800);
  };

  const filteredDocs = docs.filter(doc => {
    const matchesSearch = doc.name.toLowerCase().includes(searchTerm.toLowerCase()) ||
                          doc.type.toLowerCase().includes(searchTerm.toLowerCase());
    const matchesCategory = selectedCategory === 'ALL' || doc.type.toUpperCase() === selectedCategory;
    return matchesSearch && matchesCategory;
  });

  const categories = ['ALL', 'SHA', 'NDA', 'EMPLOYMENT', 'TERM SHEET', 'SAFE'];

  return (
    <div className="py-10 px-8 max-w-[1280px] mx-auto w-full">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 mb-8">
        <div>
          <div className="flex items-center gap-2 mb-2">
            <span className="font-mono text-[11px] font-medium tracking-[0.14em] uppercase text-teal bg-teal/10 px-2 py-0.5 rounded border border-teal/20">
              Supabase Deal Room
            </span>
            <span className="inline-flex items-center gap-1 text-[11px] font-mono text-greenok bg-greenok/10 px-2 py-0.5 rounded border border-greenok/20">
              ● Cloud Storage Synced
            </span>
          </div>
          <h1 className="font-sora text-2xl md:text-3xl font-extrabold text-white tracking-tight">
            Uploaded Deal Room Documents
          </h1>
          <p className="text-sm text-gray-400 mt-1 max-w-[600px]">
            Access and download full agreements stored in your encrypted Supabase bucket. All files are vectorized and audited against Indian corporate regulations.
          </p>
        </div>

        {/* Upload Trigger */}
        <label className="inline-flex items-center justify-center gap-2 px-4 py-2.5 bg-teal hover:bg-teal-bright text-white text-xs font-semibold font-sora rounded-xl cursor-pointer transition-all duration-200 shadow-lg shadow-teal/20 hover:scale-[1.02]">
          <Upload size={15} />
          Upload New Document
          <input type="file" multiple accept=".pdf,.doc,.docx" className="hidden" onChange={(e) => {
            alert(`File "${e.target.files[0]?.name}" queued for Supabase upload & ChromaDB indexing.`);
          }} />
        </label>
      </div>

      {/* Supabase Storage Status Banner */}
      <div className="bg-slate-mid/70 border border-slate-light/60 rounded-xl p-4 mb-8 flex flex-wrap items-center justify-between gap-4">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-lg bg-teal/15 border border-teal/30 flex items-center justify-center text-teal-bright">
            <FileText size={20} />
          </div>
          <div>
            <div className="text-xs font-semibold text-white flex items-center gap-2">
              Bucket: <span className="font-mono text-teal-bright">legal-dealroom-vault</span>
              <span className="text-[10px] font-mono bg-slate-dark px-2 py-0.5 rounded border border-slate-light/40 text-gray-400">
                AES-256 Encrypted
              </span>
            </div>
            <div className="text-[11px] text-gray-400 mt-0.5">
              Host: <span className="font-mono text-gray-300">hrfthahhweklgxkswfzb.supabase.co</span> · 5 Active Documents Ready for Download
            </div>
          </div>
        </div>

        <div className="flex items-center gap-4 text-xs font-mono text-gray-400">
          <div><span className="text-white font-bold">{docs.length}</span> Documents</div>
          <div>·</div>
          <div><span className="text-teal-bright font-bold">259</span> Indexed Clauses</div>
          <div>·</div>
          <div><span className="text-greenok font-bold">100%</span> Synced</div>
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-4 mb-6">
        {/* Search */}
        <div className="relative flex-1 max-w-[400px]">
          <Search size={15} className="absolute left-3.5 top-1/2 -translate-y-1/2 text-gray-500" />
          <input
            type="text"
            placeholder="Search by document name or type..."
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            className="w-full bg-slate-mid border border-slate-light/60 rounded-xl pl-9 pr-4 py-2 text-xs text-white placeholder-gray-500 focus:outline-none focus:border-teal transition-colors"
          />
        </div>

        {/* Categories */}
        <div className="flex items-center gap-1.5 overflow-x-auto pb-1 sm:pb-0 scrollbar-none">
          {categories.map((cat) => (
            <button
              key={cat}
              onClick={() => setSelectedCategory(cat)}
              className={`px-3 py-1.5 rounded-lg text-xs font-mono tracking-wider transition-all cursor-pointer whitespace-nowrap ${
                selectedCategory === cat
                  ? 'bg-teal text-white border border-teal-bright'
                  : 'bg-slate-mid border border-slate-light/40 text-gray-400 hover:text-white'
              }`}
            >
              {cat}
            </button>
          ))}
        </div>
      </div>

      {/* Documents Grid / Table */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
        {filteredDocs.map((doc) => {
          const highRisks = doc.risks.filter(r => r.severity === 'HIGH').length;
          const medRisks = doc.risks.filter(r => r.severity === 'MEDIUM').length;

          return (
            <div
              key={doc.id}
              className="bg-slate-mid border border-slate-light/60 hover:border-teal/50 rounded-2xl p-5 flex flex-col justify-between transition-all duration-200 hover:-translate-y-1 hover:shadow-xl group"
            >
              <div>
                {/* Card Top */}
                <div className="flex items-start justify-between gap-3 mb-3">
                  <div className="flex items-center gap-2.5">
                    <div className="w-9 h-9 rounded-xl bg-slate-dark border border-slate-light/60 flex items-center justify-center text-teal-bright">
                      <FileText size={18} />
                    </div>
                    <div>
                      <span className="font-mono text-[9px] uppercase tracking-wider bg-teal/15 text-teal-bright border border-teal/30 px-2 py-0.5 rounded-full">
                        {doc.type}
                      </span>
                    </div>
                  </div>

                  <span className="text-[10px] font-mono text-gray-500 bg-slate-dark px-2 py-0.5 rounded border border-slate-light/30">
                    PDF format
                  </span>
                </div>

                {/* Title */}
                <h3 className="font-sora text-sm font-semibold text-white group-hover:text-teal-bright transition-colors line-clamp-2 mb-2">
                  {doc.name}
                </h3>

                {/* Metadata */}
                <p className="font-mono text-[10px] text-gray-400 leading-relaxed mb-4">
                  {doc.meta}
                </p>

                {/* Risk badges */}
                <div className="flex items-center gap-2 mb-5">
                  {highRisks > 0 && (
                    <span className="text-[10px] font-mono font-medium text-redflag bg-redflag/10 border border-redflag/20 px-2 py-0.5 rounded">
                      ● {highRisks} High Risk{highRisks > 1 ? 's' : ''}
                    </span>
                  )}
                  {medRisks > 0 && (
                    <span className="text-[10px] font-mono font-medium text-gold bg-gold/10 border border-gold/20 px-2 py-0.5 rounded">
                      ● {medRisks} Medium Risk{medRisks > 1 ? 's' : ''}
                    </span>
                  )}
                  {highRisks === 0 && medRisks === 0 && (
                    <span className="text-[10px] font-mono font-medium text-greenok bg-greenok/10 border border-greenok/20 px-2 py-0.5 rounded">
                      ✓ Compliant
                    </span>
                  )}
                </div>
              </div>

              {/* Actions Footer */}
              <div className="pt-4 border-t border-slate-light/40 flex items-center gap-2">
                <button
                  onClick={() => handleDownload(doc)}
                  disabled={downloadingId === doc.id}
                  className="flex-1 inline-flex items-center justify-center gap-1.5 py-2 px-3 bg-teal/15 hover:bg-teal text-teal-bright hover:text-white border border-teal/30 hover:border-teal rounded-xl text-xs font-semibold font-sora cursor-pointer transition-all duration-150"
                  title="Download full agreement in readable PDF/Text format"
                >
                  <Download size={13} className={downloadingId === doc.id ? 'animate-bounce' : ''} />
                  {downloadingId === doc.id ? 'Downloading...' : 'Download PDF'}
                </button>

                <button
                  onClick={() => {
                    onSelectDoc(doc);
                    onNavigateToAnalysis();
                  }}
                  className="inline-flex items-center justify-center gap-1 py-2 px-3 bg-slate-dark hover:bg-slate-light/80 text-gray-300 hover:text-white border border-slate-light/60 rounded-xl text-xs font-medium cursor-pointer transition-all duration-150"
                  title="Inspect risk flags in Analysis view"
                >
                  <ExternalLink size={13} />
                  Analysis
                </button>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
